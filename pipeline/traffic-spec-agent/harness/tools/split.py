"""Activate a split of the Core library: the training-only variant (built from
`ontology/ATOMS_train.md` and `laws/audit_and_scripts/split_atoms.json`) or the full one.

`library/splits/full/` archives the full files the first time a swap happens; `library/splits/train/`
holds the training variants: `Atoms.lean` and `Ontology/*` from `nrs_tools/atoms_train.py`, and the
files that read the omitted atoms (`World`, `Decode`, `Manifest`, `Semantics`, `Primitives`, `Grounding`)
derived here by removing exactly the lines that read them. `library/splits/ACTIVE` records which
variant the Core directory currently holds; the doctor reads it.
"""
from __future__ import annotations
import json
import re
import shutil
from pathlib import Path
from ..store import paths

SPLITS = paths.LIBRARY / "splits"
ACTIVE = SPLITS / "ACTIVE"
SPLIT_ATOMS = paths.REPO / "laws" / "audit_and_scripts" / "split_atoms.json"
ATOMS, ONTOLOGY = "Vocab/Atoms.lean", "Vocab/Ontology"
WORLD, DECODE, MANIFEST = "Vocab/World.lean", "Runtime/Decode.lean", "Runtime/Manifest.lean"
SEMANTICS, PRIMITIVES, GROUNDING = "Language/Semantics.lean", "Vocab/Primitives.lean", "Runtime/Grounding.lean"
#: The split files other than `ATOMS` and `ONTOLOGY`, as paths under `TrafficSpec/Core`.
DEPENDENT = [WORLD, DECODE, MANIFEST, SEMANTICS, PRIMITIVES, GROUNDING]

#: World fields (and their JSON keys) that exist only for an atom; removed with the atom.
FIELDS_OF_ATOM: dict[str, list[tuple[str, str]]] = {
    "kin.steer_angle": [("steerAngle", "steer_angle")],
    "kin.parking_brake": [("parkingBrake", "parking_brake")],
    "sig.headlamp": [("headlamp", "headlamp")],
    "sig.position_lamp": [("positionLamp", "position_lamp")],
    "sig.reverse_lamp": [("reverseLamp", "reverse_lamp")],
    "sig.door_open": [("doorsOpen", "doors_open")],
    "dev.school_bus_signal": [("onTrack", "on_track"), ("redFlashing", "red_flashing"), ("amberFlashing", "amber_flashing"), ("stopArm", "stop_arm")],
}


def active() -> str:
    return ACTIVE.read_text().strip() if ACTIVE.exists() else "full"


def archive_full() -> None:
    """Archive the Core directory as the full variant whenever it holds one: the Core directory is
    authoritative while `full` is active, so every switch to `train` re-archives it and the training
    variant is regenerated from the edited files, never from a stale copy."""
    dst = SPLITS / "full" / "TrafficSpec" / "Core"
    if active() != "full":
        if (dst / ATOMS).exists():
            return
        raise RuntimeError("cannot archive: the Core directory does not hold the full variant")
    dst.mkdir(parents=True, exist_ok=True)
    for name in [ATOMS] + DEPENDENT:
        (dst / name).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(paths.CORE / name, dst / name)
    shutil.copytree(paths.CORE / ONTOLOGY, dst / ONTOLOGY, dirs_exist_ok=True)


def _drop_lines(text: str, predicate) -> str:
    return "".join(l for l in text.splitlines(True) if not predicate(l))


def _drop_def_block(text: str, name: str) -> str:
    """Remove `def name …` with its doc comment, up to the next top-level declaration."""
    m = re.search(rf"(?:^/--(?:(?!-/).)*?-/\n)?^def {re.escape(name)}\b.*?(?=^(?:/--|def |private def |end |-- ---))", text, re.S | re.M)
    return text[:m.start()] + text[m.end():] if m else text


def generate_train(full_dir: Path, out: Path) -> None:
    split = json.loads(SPLIT_ATOMS.read_text(encoding="utf-8"))
    atoms = set(split["test_only_atoms"])
    derived = [d.replace(".", "_") for d in split.get("test_only_primitives", [])]
    defs = {a.replace(".", "_") for a in atoms}
    fields = [f for a in atoms for f in FIELDS_OF_ATOM.get(a, [])]
    for rel in DEPENDENT:
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
    banner = "/-\n  TRAINING SPLIT variant, generated by harness/tools/split.py from the full file: the lines that read the\n  atoms the split omits are removed. Do not edit; regenerate.\n-/\n"

    def def_name_line(l: str) -> bool:
        m = re.match(r'\s*\| "([a-z]+_\w+)"', l)
        if not m:
            return False
        n = m.group(1)
        return any(n == d or n.startswith(d + "_") for d in defs) or n in derived

    # World: the fields, and every line of a projection that names one (by its field or its JSON key)
    w = (full_dir / WORLD).read_text(encoding="utf-8")
    w = _drop_lines(w, lambda l: any(re.search(rf"\b{f}\b", l) or f'"{k}"' in l for f, k in fields))
    (out / WORLD).write_text(banner + w, encoding="utf-8")
    # Decode: the keys (a dropped last field keeps the structure's closing brace)
    d = (full_dir / DECODE).read_text(encoding="utf-8")
    kept = []
    for l in d.splitlines(True):
        if any(f'"{k}"' in l for _, k in fields):
            if l.rstrip().endswith("}"):
                kept.append(re.match(r"\s*", l).group(0) + "}\n")
            continue
        kept.append(l)
    d = "".join(kept)
    (out / DECODE).write_text(banner + d, encoding="utf-8")
    # Manifest: the mask arms
    mf = (full_dir / MANIFEST).read_text(encoding="utf-8")
    mf = _drop_lines(mf, lambda l: any(f'| "{a}"' in l for a in atoms))
    (out / MANIFEST).write_text(banner + mf, encoding="utf-8")
    # Grounding: the device track relink
    g = (full_dir / GROUNDING).read_text(encoding="utf-8")
    if any(f == "onTrack" for f, _ in fields):
        g = _drop_lines(g, lambda l: "onTrack" in l)
    (out / GROUNDING).write_text(banner + g, encoding="utf-8")
    # Semantics: dispatch arms and name lists
    s = (full_dir / SEMANTICS).read_text(encoding="utf-8")
    s = _drop_lines(s, def_name_line)
    for n in sorted(defs | set(derived)):
        s = re.sub(rf'"{n}(_\w+)?",\s*', "", s)
        s = re.sub(rf',\s*"{n}(_\w+)?"', "", s)
    (out / SEMANTICS).write_text(banner + s, encoding="utf-8")
    # Primitives: the test-only ones, when any
    dv = (full_dir / PRIMITIVES).read_text(encoding="utf-8")
    for n in derived:
        dv = _drop_def_block(dv, n)
        dv = _drop_lines(dv, lambda l, n=n: re.match(rf'\s*\| "{n}"', l) is not None)
        dv = re.sub(rf'"{n}",\s*', "", dv)
        dv = re.sub(rf'\s*\| "{n}"(?=\s*\|)', "", dv)
        dv = re.sub(rf'\s*\| "{n}"(?=\s*=>)', "", dv)
    (out / PRIMITIVES).write_text(banner + dv, encoding="utf-8")


def activate(which: str) -> list[str]:
    if which not in ("train", "full"):
        raise ValueError("split must be `train` or `full`")
    archive_full()
    src = SPLITS / which / "TrafficSpec" / "Core"
    if which == "train":
        generate_train(SPLITS / "full" / "TrafficSpec" / "Core", src)
        if not (src / ATOMS).exists():
            raise RuntimeError("splits/train lacks Atoms.lean: run nrs_tools.atoms_train first")
    copied = []
    for name in [ATOMS] + DEPENDENT:
        shutil.copy2(src / name, paths.CORE / name); copied.append(name)
    for p in (paths.CORE / ONTOLOGY).glob("*.lean"):
        p.unlink()
    for p in (src / ONTOLOGY).glob("*.lean"):
        shutil.copy2(p, paths.CORE / ONTOLOGY / p.name); copied.append(f"{ONTOLOGY}/{p.name}")
    ACTIVE.write_text(which + "\n", encoding="utf-8")
    return copied
