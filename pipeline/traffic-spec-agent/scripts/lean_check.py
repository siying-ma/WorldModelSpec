"""Lean invocation: build the library and evaluate report harnesses.

Two entry points matter:

* :func:`lake_build` — does the library compile.
* :func:`eval_harness` — run a generated `#eval` harness and return its stdout,
  which is how scenario verdicts get out of Lean and into the gate.

`lake build` is used rather than the LSP because the gate needs a whole-library
answer, and because it is the same command CI would run.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path
from typing import Optional

# `path:line:col: error: message`, the shape Lean emits.
DIAG_RE = re.compile(
    r"^(?P<path>[^\s:][^:]*):(?P<line>\d+):(?P<col>\d+):\s*(?P<sev>error|warning):\s*(?P<msg>.*)$"
)


class LeanUnavailable(RuntimeError):
    """Raised when `lake` is not on PATH — a setup problem, not a spec problem."""


def _run(cmd: list[str], cwd: Path, timeout: float) -> tuple[int, str]:
    try:
        proc = subprocess.run(
            cmd, cwd=str(cwd), capture_output=True, text=True, timeout=timeout
        )
    except FileNotFoundError as exc:
        raise LeanUnavailable(
            f"could not run {cmd[0]!r}: {exc}. Install the Lean toolchain "
            f"(bash setup.sh) and re-run."
        ) from exc
    except subprocess.TimeoutExpired:
        return 124, f"TIMEOUT: {' '.join(cmd)} exceeded {timeout:.0f}s"
    return proc.returncode, (proc.stdout or "") + (proc.stderr or "")


#: Lean library root holding converted captures — the evaluation set.
#:
#: Its own root in `library/lakefile.lean`, deliberately outside `TrafficSpec/`.
#: `carla/adapter.py` writes the same string as `EVAL_NAMESPACE`; the two must
#: agree, and `run_spec doctor` checks that they do.
EVAL_LIB_ROOT = "TrafficSpecEval"

#: First line of every module `carla/adapter.py` writes. Used to recognise a
#: converted capture by content rather than by where it happens to sit, so a
#: capture written to the wrong place is still found.
ADAPTER_BANNER = "Generated by carla/adapter.py"


def captures_under(root: Path) -> list[Path]:
    """Adapter-generated trace modules anywhere under `root`.

    The invariant this serves is about WHERE a capture lives, not whether one
    exists: the evaluation set is itself Lean traces and belongs in the library.
    What must not happen is a capture inside `TrafficSpec/`, the tree the
    formalization agents are sent into — the prompts point them at Core and the
    builders, an agent with a shell reads the rest of the directory, and a
    capture it can read becomes an argument for a formalization choice. "This
    attribute occurs in the trace, so the predicate is not dead" is a claim
    about one recording that reads like a claim about the data model.

    Recognition is by banner, not by path or by size, so moving a capture
    without regenerating it does not hide it.
    """
    if not root.exists():
        return []
    found = []
    for path in sorted(root.rglob("*.lean")):
        try:
            head = path.open("r", encoding="utf-8", errors="replace").read(200)
        except OSError:
            continue
        if ADAPTER_BANNER in head:
            found.append(path)
    return found


def lake_build(library_root: Path, target: Optional[str] = None,
               timeout: float = 900.0) -> tuple[bool, str]:
    """Build the library (or one target). Returns ``(ok, combined_output)``."""
    cmd = ["lake", "build"]
    if target:
        cmd.append(target)
    code, out = _run(cmd, library_root, timeout)
    return code == 0, out


# A node harness evaluates one rule over its own scenarios; the node default is
# generous for that. A *capture* harness evaluates EVERY registered rule over a
# whole capture, and its cost is (groundings x frames^2), because `Trace` is a
# `List Scene` and scene lookup is O(i). That is two orders of magnitude more
# work, and when it exceeded the node timeout the capture was reported as
# unevaluable rather than as slow — a silent loss of the only check that is
# independent of the agent. This ceiling exists to make that outcome hard to
# reach; it is sized as an order of magnitude and grows with library size and
# capture length, so re-check it rather than assuming it still fits.
CAPTURE_EVAL_TIMEOUT = 1800.0


def eval_harness(library_root: Path, harness: Path,
                 timeout: float = 300.0) -> tuple[bool, str]:
    """Elaborate a standalone `.lean` file, returning its `#eval` output.

    The file may live outside the library tree; imports still resolve because
    `lake env` supplies LEAN_PATH.
    """
    code, out = _run(
        ["lake", "env", "lean", str(harness.resolve())], library_root, timeout
    )
    return code == 0, out


def parse_diagnostics(output: str, severity: str = "error") -> list[str]:
    """Extract `file:line:col: severity: message` diagnostics from Lean output.

    Lean continues a multi-line message on following lines; those are attached
    to the diagnostic they belong to so an error's context is not lost.
    """
    found: list[str] = []
    current: Optional[list[str]] = None
    for line in output.splitlines():
        m = DIAG_RE.match(line)
        if m:
            if current is not None:
                found.append("\n".join(current))
                current = None
            if m.group("sev") == severity:
                current = [line.rstrip()]
        elif current is not None:
            if line.strip():
                current.append(line.rstrip())
            else:
                found.append("\n".join(current))
                current = None
    if current is not None:
        found.append("\n".join(current))
    return found


def first_errors(output: str, limit: int = 5) -> str:
    """A compact error digest for an agent-facing verdict message."""
    errors = parse_diagnostics(output, "error")
    if not errors:
        # A build can fail without a positional diagnostic (e.g. a Lake error).
        tail = [ln for ln in output.strip().splitlines() if ln.strip()][-limit:]
        return "\n".join(tail) if tail else "(no diagnostics captured)"
    shown = errors[:limit]
    extra = len(errors) - len(shown)
    text = "\n\n".join(shown)
    if extra > 0:
        text += f"\n\n... and {extra} more error(s)."
    return text


def write_node_harness(harness_path: Path, module: str, namespace: str,
                       witness_module: str, witness_namespace: str) -> None:
    """Emit the `#eval` harness that reports one node's witness verdicts.

    Imports two modules, because a rule and its witnesses are two files: the
    rule declares `entry`, the witness module declares `scenarios`. Importing
    the witness is enough — it imports the rule itself — but both are named so
    a missing witness module fails here with the module name rather than as an
    unresolved identifier inside the rule's namespace.

    Prints the tab-separated report defined in `Core/Grounding.lean`, which
    `tools/check_spec.py` parses.
    """
    harness_path.parent.mkdir(parents=True, exist_ok=True)
    harness_path.write_text(
        "\n".join([
            "/- Generated by scripts/lean_check.py. Do not edit. -/",
            f"import {module}",
            f"import {witness_module}",
            "",
            f"#eval TrafficSpec.reportIO {namespace}.entry "
            f"{witness_namespace}.scenarios",
            "",
        ]),
        encoding="utf-8",
    )


def write_library_harness(harness_path: Path) -> None:
    """Emit the harness that re-reports every rule's witnesses.

    Imports the witness root rather than the index: `TrafficSpec.Index` is what
    an application loads and carries no witnesses at all.
    """
    harness_path.parent.mkdir(parents=True, exist_ok=True)
    harness_path.write_text(
        "\n".join([
            "/- Generated by scripts/lean_check.py. Do not edit. -/",
            "import TrafficSpecWitness",
            "",
            "#eval TrafficSpec.witnessReportIO",
            "",
        ]),
        encoding="utf-8",
    )


def write_capture_harness(harness_path: Path, module: str, trace: str) -> None:
    """Emit the harness that evaluates every registered rule against a captured
    trace, rather than against the rules' own declared scenarios.

    One `CAP` line per rule: node id, law refs, grounding count, verdict, and
    the formula's frame span.

    Two columns are load-bearing. The **grounding count** — a rule that grounds
    zero times on a capture has not been tested by it, and reporting that as
    agreement with a `not_applicable` label is the difference between a
    benchmark and a rubber stamp. And the **span**: a capture shorter than it
    cannot clear the rule, because `loopBounded` reads a window running off the
    end of the trace as false and the safety shape `□ (¬ₛ .bounded n bad)` is
    then satisfied whatever the footage shows.
    """
    harness_path.parent.mkdir(parents=True, exist_ok=True)
    harness_path.write_text(
        "\n".join([
            "/- Generated by scripts/lean_check.py. Do not edit. -/",
            "import TrafficSpec.Index",
            f"import {module}",
            "",
            "open TrafficSpec",
            "",
            "def captureReportIO : IO Unit := do",
            f"  let τ : Trace := {trace}",
            "  IO.println s!\"FRAMES\\t{τ.length}\"",
            "  for r in allRules do",
            "    let refs := String.intercalate \",\" r.lawRefs",
            # Liveness is computed ONCE and the verdict derived from it, rather
            # than calling `checkVacuityAware`, which recomputes it internally.
            # The two together evaluated every rule's antecedent over the whole
            # trace twice per capture — the same arithmetic as the check they
            # were meant to make cheaper. Inlining its two cases keeps the
            # verdict identical (`some 0 => true`, otherwise `check`) at one
            # pass.
            "    let liveCount := r.livenessCount τ",
            "    let live := match liveCount with",
            "      | some n => toString n",
            "      | none   => \"?\"",
            "    let verdict := match liveCount with",
            "      | some 0 => true",
            "      | _      => r.check τ",
            "    IO.println s!\"CAP\\t{r.nodeId}\\t{refs}\\t{r.groundingCount τ}"
            "\\t{verdict}\\t{r.frameSpan}\\t{live}\"",
            "",
            "#eval captureReportIO",
            "",
        ]),
        encoding="utf-8",
    )
