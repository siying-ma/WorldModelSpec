"""Generate `library/TrafficSpec/Carla/Sample.lean` from the data model.

Why this is generated
---------------------
The fixture's job is to answer one question the gate cannot answer any other
way: can a rule's binders bind at all against a scene built to the generator's
own type and coverage rules? A rule's own `scenarios` are written by the same
agent that chose the formalization, so they agree with a misreading; the fixture
is the one trace that agent did not author.

That verdict is only sound if the fixture covers the WHOLE model. A gap in it
becomes a false accusation against a correct rule — and that has happened: an
earlier hand-written fixture carried three of the actor types the generator
emits, so every rule over a pedestrian, cyclist, bus, truck, motorcycle or van
looked unable to ground, and nothing detected it because the fixture was judged
by whether it looked realistic.

Hand-authoring has cost twice. `tools/check_spec.py` records the second: a
hand-maintained list of what the fixture contained "described our own fixture
rather than anything CARLA produces, and had already drifted".

So the content is derived. Entity types, relation labels, the proximity-capable
types and the distance bands all come from `Core/Scene.lean`; the angular labels
are what remains after the structural, governance and distance labels are
removed, rather than a list repeated here. Adding a constructor to `Scene.lean`
therefore extends the fixture on the next `run_spec sample`, and `run_spec
doctor` fails if the checked-in file no longer matches what this module emits.

What is NOT derived is the scene's topology — which lane is adjacent, which
leads into the junction — and the choice of builder per entity type. Both are
design decisions of the fixture, recorded below rather than inferred, and both
are validated: a type with no builder mapping falls back to `mkActor` rather
than being silently dropped, and a builder this module names must exist in
`Core/Builders.lean`.
"""
from __future__ import annotations

import re
from pathlib import Path

HEADER_MARK = "Generated by scripts/sample_sync.py"

# Structural labels, whose wiring is the fixture's topology rather than a
# derived fact. Everything not listed here and not a distance band is angular.
STRUCTURAL = {"isIn", "opposes", "travelsTo", "laneChange", "controls", "mayAffect"}


def _ctors(text: str, name: str) -> list[str]:
    """Constructor names of an `inductive` block, in declaration order."""
    m = re.search(rf"inductive {name} where\n(.*?)\n\s*deriving", text, re.S)
    if not m:
        return []
    return re.findall(r"^\s*\|\s*(\w+)", m.group(1), re.M)


def _group(text: str, name: str) -> list[str]:
    m = re.search(rf"^def {name} : List EntityType :=\n\s*\[([^\]]*)\]", text, re.M)
    if not m:
        return []
    return [x.strip().lstrip(".") for x in m.group(1).replace("\n", " ").split(",") if x.strip()]


def _bands(text: str) -> list[str]:
    m = re.search(r"^def distanceBands : List \(RelLabel × Nat\) :=\n\s*\[(.*?)\]", text, re.M | re.S)
    if not m:
        return []
    return re.findall(r"\(\.(\w+),", m.group(1))


# How each entity type is constructed, and with what. `mkActor` is the fallback,
# so a type added to `Scene.lean` and not listed here still reaches the fixture.
# Every function named must exist in `Core/Builders.lean`; `render` checks it.
BUILDERS: dict[str, str] = {
    "lane":            'mkLane {id} "{name}"',
    "road":            'mkRoad {id} "{name}"',
    "junction":        'mkJunction {id} "{name}"',
    "offRoad":         "mkOffRoad {id}",
    "trafficLight":    'mkTrafficLight {id} "{name}" "Red"',
    "stopSign":        'mkStopSign {id} "{name}"',
    "speedLimitSign":  'mkSpeedLimitSign {id} "{name}" "30"',
    "landmark":        'mkSpeedLimitLandmark {id} "{name}" "274" "30" "km/h"',
}
# Types with no dedicated builder and no base class of their own.
GENERIC = 'mkEntity {id} .{ty} [("name", "{name}")]'

# Placeholder identifiers, following the generator's own naming so that
# predicates reading a name's shape behave as they would on real output:
# `Lane <road>_<±lane>`, `Road <n>`, `Junction <n>`, `<base_class>_<counter>`.
STRUCTURE_NAMES = {
    "lane": ["Lane a_-1", "Lane a_-2", "Lane a_+1", "Lane b_-1"],
    "road": ["Road a", "Road b"],
    "junction": ["Junction j"],
    "offRoad": ["Off Road"],
}


def _name_for(ty: str, base: dict[str, str], seen: dict[str, int]) -> str:
    if ty in STRUCTURE_NAMES:
        i = seen.get(ty, 0)
        return STRUCTURE_NAMES[ty][min(i, len(STRUCTURE_NAMES[ty]) - 1)]
    if ty == "trafficLight":
        return "traffic.traffic_light_0"
    if ty == "stopSign":
        return "traffic.stop_0"
    if ty == "speedLimitSign":
        return "traffic.speed_limit_30_0"
    if ty == "landmark":
        return "landmark_OpenDRIVE_274_0"
    return f"{base.get(ty, ty)}_0"


def _base_classes(scene: str) -> dict[str, str]:
    """`EntityType.baseClass`, so actor names match the generator's scheme."""
    out: dict[str, str] = {}
    m = re.search(r"def EntityType\.baseClass : EntityType → Option String\n(.*?)\n\n", scene, re.S)
    if m:
        for ty, base in re.findall(r"\|\s*\.(\w+)\s*=>\s*some \"(\w+)\"", m.group(1)):
            out[ty] = base
    return out


# `toLeftOf` / `toRightOf` are the one label pair the generator emits at two
# different arities — between adjacent lanes of a road, and between the ego and
# another actor. The fixture wires the lane form, which is where they carry
# information the four direct/side labels do not.
LATERAL = {"toLeftOf", "toRightOf"}

# How many instances of a structure type the topology needs. Every other type
# appears exactly once.
MULTIPLICITY = {"lane": 4, "road": 2}


def build(scene_src: str) -> dict:
    """The fixture's content, derived from `Core/Scene.lean`."""
    types = _ctors(scene_src, "EntityType")
    labels = _ctors(scene_src, "RelLabel")
    bands = _bands(scene_src)
    prox = _group(scene_src, "proximityTypes")
    base = _base_classes(scene_src)
    if not (types and labels and bands and prox):
        raise SystemExit("sample_sync: Core/Scene.lean did not yield the data model")
    angular = [l for l in labels if l not in STRUCTURAL and l not in bands and l not in LATERAL]

    ids: dict[str, list[int]] = {}
    entities: list[tuple[str, str]] = []          # (lean expression, comment)
    n = 1
    ids["ego"] = [n]
    entities.append((f'mkEgo {n} .car "8.000000" "0.000000" "0.300000" "0.000000" '
                     f'"0.000000" "0.000000" "true" "false" "false"',
                     "the ego vehicle — ego-ness is an attribute, not a type"))
    n += 1
    seen: dict[str, int] = {}
    for ty in types:
        ids[ty] = []
        for _ in range(MULTIPLICITY.get(ty, 1)):
            name = _name_for(ty, base, seen)
            seen[ty] = seen.get(ty, 0) + 1
            tmpl = BUILDERS.get(ty)
            if tmpl is None:
                tmpl = (GENERIC if base.get(ty) is None
                        else 'mkActor {id} "{name}" .{ty}')
            entities.append((tmpl.format(id=n, name=name, ty=ty),
                             "no proximity edge: absent from the relation table"
                             if ty not in prox and base.get(ty) and ty not in BUILDERS else ""))
            ids[ty].append(n)
            n += 1
    return {"types": types, "labels": labels, "bands": bands, "prox": prox,
            "angular": angular, "ids": ids, "entities": entities}


def relations(d: dict) -> list[tuple[str, str]]:
    """The fixture's wiring: every relation label, once, on the coverage rules.

    The topology is a design choice; the COVERAGE is not. Proximity and angular
    edges run from the ego and only to the types in `proximityTypes`, so a rule
    binding a van or a generic vehicle by distance grounds zero here exactly as
    it would on generator output.
    """
    i = d["ids"]
    ego = i["ego"][0]
    lane_ego, lane_adj, lane_opp, lane_junc = i["lane"]
    road, road_junc = i["road"]
    junction, off_road = i["junction"][0], i["offRoad"][0]
    structure = set(_group_types(d))
    out: list[tuple[str, str]] = []

    out.append(("", "isIn, at all three levels it is overloaded across"))
    out.append((f"mkRel {ego} .isIn {lane_ego}", ""))
    lane_cycle = [lane_ego, lane_adj, lane_opp, lane_junc]
    k = 0
    for ty in d["types"]:
        if ty in structure or ty in ("trafficLight", "stopSign", "speedLimitSign", "landmark"):
            continue
        for eid in i[ty]:
            if ty == "pedestrian":
                out.append((f"mkRel {eid} .isIn {off_road}", "an entity in no driving lane"))
            elif ty == "junctionBoundary":
                out.append((f"mkRel {eid} .isIn {junction}", ""))
            else:
                out.append((f"mkRel {eid} .isIn {lane_cycle[k % len(lane_cycle)]}", ""))
                k += 1
    for l in (lane_ego, lane_adj, lane_opp):
        out.append((f"mkRel {l} .isIn {road}", ""))
    out.append((f"mkRel {lane_junc} .isIn {road_junc}", ""))
    out.append((f"mkRel {road_junc} .isIn {junction}", ""))

    out.append(("", "lateral: asymmetric between same-direction lanes, mutual between opposing"))
    out += [(f"mkRel {lane_adj} .toRightOf {lane_ego}", ""),
            (f"mkRel {lane_ego} .toLeftOf {lane_adj}", ""),
            (f"mkRel {lane_ego} .opposes {lane_opp}", ""),
            (f"mkRel {lane_opp} .opposes {lane_ego}", "")]

    out.append(("", "connectivity: the approach leads into the junction lane"))
    out += [(f"mkRel {lane_ego} .travelsTo {lane_junc}", ""),
            (f"mkRel {lane_adj} .travelsTo {lane_junc}", ""),
            (f"mkRel {lane_ego} .laneChange {lane_adj}", "")]

    out.append(("", "governance: device to lane, never device to vehicle"))
    out += [(f"mkRel {i['trafficLight'][0]} .controls {lane_junc}", ""),
            (f"mkRel {i['stopSign'][0]} .controls {lane_ego}", ""),
            (f"mkRel {i['landmark'][0]} .mayAffect {lane_ego}", ""),
            (f"mkRel {i['speedLimitSign'][0]} .isIn {lane_ego}",
             "a limit sign has no governance edge — bounding-box overlap only")]

    out.append(("", "proximity: one band each, ego to every proximity-capable base class"))
    for n, band in enumerate(d["bands"]):
        out.append((f"mkRel {ego} .{band} {i[d['prox'][n % len(d['prox'])]][0]}", ""))
    out.append(("", "angular: the direct/side split, both ahead and behind"))
    for n, lbl in enumerate(d["angular"]):
        out.append((f"mkRel {ego} .{lbl} {i[d['prox'][n % len(d['prox'])]][0]}", ""))
    return out


def _group_types(d: dict) -> list[str]:
    return [t for t in d["types"] if t in ("lane", "road", "junction", "offRoad")]


TEMPLATE = '''/-
  TrafficSpec.Carla.Sample
  The coverage fixture the gate measures reachability against.

  MANAGED FILE — {mark}. Do not edit by hand: it is
  derived from `Core/Scene.lean`, so a constructor added there reaches this
  fixture on the next `run_spec sample`, and `run_spec doctor` fails when the
  checked-in file no longer matches what the generator emits.

  PURPOSE. `tools/check_spec.py` evaluates every rule against this trace and
  reports the GROUNDING COUNT. Zero means the rule's binders cannot bind at all
  against a scene built to the generator's own type and coverage rules, which is
  nearly always a defect in the specification rather than a property of the
  world. A rule's own scenarios cannot answer this: they are written by the same
  agent that chose the formalization, so they agree with a misreading.

  WHAT IT IS NOT. It is not a sample of simulator output and does not depict a
  situation. No arrangement here asserts that anything occurs in any map.

  WHAT IT IS. One entity of every `EntityType` and one edge of every `RelLabel`,
  wired to the coverage rules the abstraction follows — proximity and angular
  edges from the ego only and only to the base classes `proximityTypes` covers,
  governance from a device to a lane, `isIn` at its three levels. The
  arrangement is chosen to make every binder reachable, so that a zero count
  means something.

  Deliberately static. The count depends on which entities and relations are
  present, not on how they change, so the scene is replicated across frames.
-/
import TrafficSpec.Core.Builders

namespace TrafficSpec.Carla

open TrafficSpec

/-- Every entity type the generator emits, once each — plus the extra lane and
    road nodes the topology needs. Names follow the generator's own composition,
    because `carla/adapter.py` keys entities by name and several predicates read
    a name's shape. The identifiers are placeholders. -/
private def entities : List Entity :=
{entities}

/-- Every relation label, wired to the generator's coverage rules. -/
private def relations : List Relation :=
{relations}

/-- The single scene the fixture replicates. -/
private def scene : Scene := frame entities relations

/-- Fixture length, in frames. Not a claim about any recording: it bounds which
    rules the CARLA line can report on, since a rule whose `frameSpan` exceeds
    it reports `short`. Expressed through `secondsToFrames` so it tracks the
    capture rate rather than restating it. -/
def sampleFrames : Nat := TrafficSpec.secondsToFrames 5

/-- The coverage trace. -/
def sampleTrace : Trace := List.replicate sampleFrames scene

end TrafficSpec.Carla
'''


def _lean_list(items: list[tuple[str, str]]) -> str:
    lines, first = [], True
    for expr, comment in items:
        if not expr:
            lines.append(f"  -- {comment}")
            continue
        lead = "  [ " if first else "  , "
        first = False
        lines.append(f"{lead}{expr}" + (f"   -- {comment}" if comment else ""))
    lines.append("  ]")
    return "\n".join(lines)


def render(library_root: Path) -> str:
    scene_src = (library_root / "TrafficSpec" / "Core" / "Scene.lean").read_text(encoding="utf-8")
    builders = (library_root / "TrafficSpec" / "Core" / "Builders.lean").read_text(encoding="utf-8")
    d = build(scene_src)
    for tmpl in list(BUILDERS.values()) + [GENERIC, 'mkActor {id} "{name}" .{ty}',
                                           "mkEgo", "mkRel", "frame"]:
        fn = tmpl.split()[0] if " " in tmpl else tmpl
        if f"def {fn} " not in builders and f"def {fn}\n" not in builders:
            raise SystemExit(f"sample_sync: Core/Builders.lean defines no `{fn}`")
    return TEMPLATE.format(mark=HEADER_MARK,
                           entities=_lean_list(d["entities"]),
                           relations=_lean_list(relations(d)))


def sync(library_root: Path) -> tuple[Path, bool]:
    """Write the fixture. Returns the path and whether it changed."""
    path = library_root / "TrafficSpec" / "Carla" / "Sample.lean"
    text = render(library_root)
    changed = (not path.exists()) or path.read_text(encoding="utf-8") != text
    if changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return path, changed
