def strip_annotations(text: str) -> str:
    """Remove the bracketed id annotations the corpus adds to verbatim text."""
    return re.sub(r"\[[A-Z]+-[^\]]+\]", "", text)


def scan(text: str) -> tuple[set[str], set[str]]:
    t = strip_annotations(text).lower()
    atoms = {a for a, pat in ATOMS.items() if re.search(pat, t)}
    values = {v for v, pat in VALUES.items() if re.search(pat, t)}
    return atoms, values
